export default async function(req: Request): Promise<Response> {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });
    if (!['admin', 'superadmin'].includes(user.role)) {
      return Response.json({ error: 'Forbidden — admin only' }, { status: 403 });
    }

    const { accessToken } = await base44.asServiceRole.connectors.getConnection('github');
    if (!accessToken) return Response.json({ error: 'GitHub not connected' }, { status: 401 });

    const headers = {
      Authorization: `Bearer ${accessToken}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'User-Agent': 'ThreatPulse-PortBot/1.0'
    };

    const gh = (path, opts) => fetch(`${API}${path}`, { headers, ...opts }).then(async (r) => {
      const text = await r.text();
      let data = null;
      try { data = text ? JSON.parse(text) : null; } catch { data = text; }
      if (!r.ok) throw new Error(`GitHub ${r.status} ${path}: ${typeof data === 'string' ? data : JSON.stringify(data?.message || data)}`);
      return data;
    });

    // 1. Get default branch SHA
    const repoInfo = await gh(`/repos/${REPO}`);
    const defaultBranch = repoInfo.default_branch;
    const defRef = await gh(`/repos/${REPO}/git/refs/heads/${defaultBranch}`);
    const parentSha = defRef.object.sha;

    // 2. Get base tree
    const parentCommit = await gh(`/repos/${REPO}/git/commits/${parentSha}`);
    const baseTree = parentCommit.tree.sha;

    // 6. Assemble files — only the 3 route files need the import fix
    const files = [
      { path: 'nextjs_space/app/api/integrations/confluence/route.ts', content: ROUTE_GET_POST },
      { path: 'nextjs_space/app/api/integrations/confluence/[id]/route.ts', content: ROUTE_PATCH_DELETE },
      { path: 'nextjs_space/app/api/integrations/confluence/test/route.ts', content: ROUTE_TEST },
    ];

    // 7. Create tree
    const tree = await gh(`/repos/${REPO}/git/trees`, {
      method: 'POST',
      body: JSON.stringify({
        base_tree: baseTree,
        tree: files.map((f) => ({ path: f.path, mode: '100644', type: 'blob', content: f.content }))
      })
    });

    // 8. Create commit
    const commit = await gh(`/repos/${REPO}/git/commits`, {
      method: 'POST',
      body: JSON.stringify({ message: COMMIT_MSG, tree: tree.sha, parents: [parentSha] })
    });

    // 9. Create branch
    try {
      await gh(`/repos/${REPO}/git/refs/heads/${BRANCH}`, {
        method: 'PATCH',
        body: JSON.stringify({ sha: commit.sha })
      });
    } catch {
      await gh(`/repos/${REPO}/git/refs`, {
        method: 'POST',
        body: JSON.stringify({ ref: `refs/heads/${BRANCH}`, sha: commit.sha })
      });
    }

    // 10. Create PR
    const pr = await gh(`/repos/${REPO}/pulls`, {
      method: 'POST',
      body: JSON.stringify({ title: PR_TITLE, head: BRANCH, base: defaultBranch, body: PR_BODY })
    });

    // 11. Merge PR
    let mergeResult = null;
    try {
      mergeResult = await gh(`/repos/${REPO}/pulls/${pr.number}/merge`, {
        method: 'PUT',
        body: JSON.stringify({ merge_method: 'squash', commit_title: `${PR_TITLE} (#${pr.number})` })
      });
    } catch (mergeErr) {
      // If merge fails (e.g. branch protection), return PR info so user can merge manually
      return Response.json({
        ok: true,
        pr: { number: pr.number, url: pr.html_url },
        merged: false,
        mergeError: mergeErr.message,
        message: 'PR created but auto-merge failed — merge manually'
      });
    }

    return Response.json({
      ok: true,
      branch: BRANCH,
      commitSha: commit.sha,
      files: files.length,
      pr: { number: pr.number, url: pr.html_url },
      merged: mergeResult?.merged || true,
      mergeSha: mergeResult?.sha
    });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
}